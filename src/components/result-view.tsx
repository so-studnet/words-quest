import Link from "next/link";
import type { LookupResult } from "@/lib/domain/lookup-result";
import { SpeakButton } from "./speak-button";

const KIND_LABELS: Record<LookupResult["kind"], string> = {
  word: "Word",
  phrase: "Phrase / idiom",
  sentence: "Sentence",
};

function href(text: string) {
  return `/?q=${encodeURIComponent(text)}`;
}

function WordChips({ label, words }: { label: string; words: string[] }) {
  if (words.length === 0) return null;
  return (
    <div className="mt-3">
      <h4 className="text-xs font-semibold uppercase tracking-wide text-muted">{label}</h4>
      <ul className="mt-1 flex flex-wrap gap-2">
        {words.map((w) => (
          <li key={w}>
            <Link
              href={href(w)}
              className="inline-block rounded-full border border-border px-3 py-1 text-sm hover:border-accent"
            >
              {w}
            </Link>
          </li>
        ))}
      </ul>
    </div>
  );
}

export function ResultView({ result }: { result: LookupResult }) {
  return (
    <article className="flex flex-col gap-4" aria-live="polite">
      <header>
        <p className="text-sm text-muted">{KIND_LABELS[result.kind]}</p>
        <div className="mt-1 flex items-start gap-3">
          <h2 className="min-w-0 flex-1 text-3xl font-bold break-words">{result.query}</h2>
          <SpeakButton text={result.query} label="Listen" />
        </div>
        {result.phonetic && <p className="mt-1 text-lg text-muted">{result.phonetic}</p>}
        {result.paraphrase && <p className="mt-3 text-lg">{result.paraphrase}</p>}
      </header>

      {result.senses.length > 0 && (
        <ol className="flex flex-col gap-3">
          {result.senses.map((s, i) => (
            <li key={i} className="rounded-xl border border-border p-4">
              {s.partOfSpeech && (
                <p className="text-sm font-semibold italic text-accent">{s.partOfSpeech}</p>
              )}
              <p className="mt-1">
                <span className="mr-2 text-muted">{i + 1}.</span>
                {s.definition}
              </p>
              {s.examples.length > 0 && (
                <ul className="mt-2 flex flex-col gap-1 border-l-2 border-border pl-3 text-muted">
                  {s.examples.map((ex) => (
                    <li key={ex} className="flex items-start gap-2">
                      <span className="min-w-0 flex-1">“{ex}”</span>
                      <SpeakButton text={ex} label="Listen to example" size="sm" />
                    </li>
                  ))}
                </ul>
              )}
              <WordChips label="Synonyms" words={s.synonyms} />
              <WordChips label="Antonyms" words={s.antonyms} />
            </li>
          ))}
        </ol>
      )}

      {result.notes.length > 0 && (
        <section className="rounded-xl border border-border p-4">
          <h3 className="font-semibold">Notes</h3>
          <ul className="mt-2 list-disc pl-5">
            {result.notes.map((n) => (
              <li key={n}>{n}</li>
            ))}
          </ul>
        </section>
      )}

      {(result.synonyms.length > 0 || result.antonyms.length > 0) && (
        <section className="rounded-xl border border-border p-4">
          <h3 className="font-semibold">{result.kind === "word" ? "Related words" : "Similar expressions"}</h3>
          <WordChips label={result.kind === "word" ? "Synonyms" : "Similar"} words={result.synonyms} />
          <WordChips label={result.kind === "word" ? "Antonyms" : "Opposite"} words={result.antonyms} />
        </section>
      )}

      <p className="text-xs text-muted">Generated by AI. It can make mistakes.</p>
    </article>
  );
}
